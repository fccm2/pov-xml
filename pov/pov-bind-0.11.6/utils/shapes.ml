type pos = float * float * float
type triangle = pos * pos * pos

type uv = float * float
type triangle_2d = uv * uv * uv
type triangle_uv = triangle * triangle_2d

let get_octahedron ~s ~h = [
  ( (-. s, 0.0,    s), (0.0, h, 0.0), (   s, 0.0,    s) );
  ( (   s, 0.0,    s), (0.0, h, 0.0), (   s, 0.0, -. s) );
  ( (   s, 0.0, -. s), (0.0, h, 0.0), (-. s, 0.0, -. s) );
  ( (-. s, 0.0, -. s), (0.0, h, 0.0), (-. s, 0.0,    s) );

  ( (-. s, 0.0, -. s), (0.0, -. h, 0.0), (   s, 0.0, -. s) );
  ( (-. s, 0.0,    s), (0.0, -. h, 0.0), (-. s, 0.0, -. s) );
  ( (   s, 0.0,    s), (0.0, -. h, 0.0), (-. s, 0.0,    s) );
  ( (   s, 0.0, -. s), (0.0, -. h, 0.0), (   s, 0.0,    s) );
]

let get_pyramid ~s ~h = [
  ( (-. s, 0.0,    s), (0.0, h, 0.0), (   s, 0.0,    s) );
  ( (   s, 0.0,    s), (0.0, h, 0.0), (   s, 0.0, -. s) );
  ( (   s, 0.0, -. s), (0.0, h, 0.0), (-. s, 0.0, -. s) );
  ( (-. s, 0.0, -. s), (0.0, h, 0.0), (-. s, 0.0,    s) );

  ( (-. s, 0.0, -. s), (   s, 0.0, -. s), (-. s, 0.0, -. s) );
  ( (-. s, 0.0,    s), (-. s, 0.0,    s), (   s, 0.0,    s) );
