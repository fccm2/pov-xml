let get_tetrahedron ~s ~h =
  let p1 = (-. s,    h,  0.0) in
  let p2 = (   s,    h,  0.0) in
  let p3 = ( 0.0, -. h,    s) in
  let p4 = ( 0.0, -. h, -. s) in
  [
    (p1, p2, p3);
    (p1, p2, p4);
    (p2, p3, p4);
    (p3, p1, p4);
  ]

let get_icosahedron () =
  let phi = 1.618 in
  let p0  = (0.0,  1.0, phi) in
  let p1  = (0.0, -1.0, phi) in
  let p2  = ( 1.0, phi, 0.0) in
  let p3  = (-1.0, phi, 0.0) in
  let p4  = (  phi, 0.0, 1.0) in
  let p5  = (-.phi, 0.0, 1.0) in
  let p6  = (0.0,-1.0, -.phi) in
  let p7  = (0.0, 1.0, -.phi) in
  let p8  = (-1.0, -.phi, 0.0) in
  let p9  = ( 1.0, -.phi, 0.0) in
  let p10 = (-.phi, 0.0, -1.0) in
  let p11 = (  phi, 0.0, -1.0) in
  [
    (p0,p5,p1); (p0,p3,p5); (p0,p2,p3); (p0,p4,p2); (p0,p1,p4);
    (p1,p5,p8); (p5,p3,p10); (p3,p2,p7); (p2,p4,p11); (p4,p1,p9);
    (p7,p11,p6); (p11,p9,p6); (p9,p8,p6); (p8,p10,p6); (p10,p7,p6);
    (p2,p11,p7); (p4,p9,p11); (p1,p8,p9); (p5,p10,p8); (p3,p7,p10);
  ]


